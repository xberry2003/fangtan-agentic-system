// Run against the local studio; all uploaded/recorded content is synthetic.
const {chromium} = require('../frontend/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.TICHA_TEST_URL || 'http://127.0.0.1:19001';
const out = path.resolve(__dirname, '../data/qa');
fs.mkdirSync(out, {recursive: true});
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream']});
  const context = await browser.newContext({viewport: {width: 1600, height: 1000}, permissions: ['microphone']});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByRole('textbox', {name: '搜索项目'}).waitFor();
  assert.equal(await page.getByRole('button', {name: '开始录音', exact: true}).count(), 0);
  await page.getByRole('button', {name: '移动光标，探索底图'}).click();
  await page.screenshot({path: path.join(out, '01-project-selection.png'), fullPage: true});
  await page.getByRole('button', {name: '新建项目', exact: true}).click();
  assert.equal(await page.getByRole('button', {name: '创建项目', exact: true}).isDisabled(), true);
  await page.getByLabel('给新项目起个名字').fill('QA · 凌西物流园升级改造');
  await page.getByRole('button', {name: '创建项目', exact: true}).click();
  await page.getByRole('button', {name: '打开工作台', exact: true}).waitFor();
  const first = new URL(page.url()).searchParams.get('project');
  assert(first);
  await page.reload();
  await page.getByRole('button', {name: '打开工作台', exact: true}).waitFor();
  assert.equal(await page.evaluate(() => localStorage.getItem('ticha-studio:last-project')), first);
  await page.getByRole('button', {name: '移动光标，探索底图'}).click();
  await page.locator('.hero-subtitle.is-done').waitFor();
  await page.screenshot({path: path.join(out, '02-project-home.png'), fullPage: true});
  assert.equal(await page.getByText(/旧版|用户与市场调研|企业访谈/).count(), 0);
  await page.getByRole('button', {name: '切换项目', exact: true}).click();
  await page.getByRole('button', {name: '新建项目', exact: true}).click();
  await page.getByLabel('给新项目起个名字').fill('QA · 上海新能源汽车调研');
  await page.getByRole('button', {name: '创建项目', exact: true}).click();
  await page.waitForURL(url => !!url.searchParams.get('project') && url.searchParams.get('project') !== first);
  await page.getByRole('button', {name: '打开工作台', exact: true}).waitFor();
  const second = new URL(page.url()).searchParams.get('project');
  assert.notEqual(first, second);
  await page.goto(base);
  await page.getByRole('button', {name: '打开工作台', exact: true}).waitFor();
  assert.equal(new URL(page.url()).searchParams.get('project'), second);
  await page.getByRole('button', {name: '切换项目', exact: true}).click();
  await page.getByRole('button', {name: /QA · 凌西物流园升级改造/}).first().click();
  await page.getByRole('button', {name: '上传材料', exact: true}).click();
  await page.locator('input[type=file]').setInputFiles({name: 'QA-访谈材料.txt', mimeType: 'text/plain', buffer: Buffer.from('合成材料，不含真实受访者资料。')});
  await page.getByText('QA-访谈材料.txt', {exact: true}).waitFor();
  await page.getByRole('button', {name: '体察项目首页', exact: true}).click();
  await page.getByRole('button', {name: '开始录音', exact: true}).click();
  await page.getByLabel('已取得受访者录音同意').check();
  await page.getByLabel('访谈名称', {exact: true}).fill('QA-合成录音');
  await page.getByRole('button', {name: '开始录音', exact: true}).click();
  await page.getByRole('button', {name: '结束并保存', exact: true}).waitFor();
  await page.waitForTimeout(1200);
  await page.getByRole('button', {name: '结束并保存', exact: true}).click();
  await page.getByText('原始录音已保存到项目材料', {exact: true}).waitFor();
  await page.getByRole('button', {name: '材料', exact: true}).click();
  await page.getByText('QA-合成录音.webm', {exact: true}).waitFor();
  await page.getByRole('button', {name: '体察项目首页', exact: true}).click();
  await page.getByLabel('在这个项目里，你想做什么？').fill('帮我准备三个问题');
  await page.getByRole('button', {name: '发送消息', exact: true}).click();
  await page.getByRole('alert').filter({hasText: '尚未配置 AI 服务'}).waitFor();
  await page.getByRole('button', {name: '关闭提示'}).click();
  await page.getByRole('button', {name: '体察项目首页', exact: true}).click();
  await page.setViewportSize({width: 390, height: 844});
  await page.locator('.hero-subtitle.is-done').waitFor();
  assert(await page.locator('.hero-subtitle').evaluate(el => parseFloat(getComputedStyle(el).fontSize) <= 18));
  await page.getByRole('button', {name: '移动光标，探索底图'}).click();
  await page.screenshot({path: path.join(out, '03-mobile-home.png'), fullPage: true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', {name: '打开工作台', exact: true}).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.goto(base + '/?project=missing');
  await page.getByRole('textbox', {name: '搜索项目'}).waitFor();
  assert.equal(errors.length, 0, errors.join('\n'));
  fs.writeFileSync(path.join(out, 'projects.json'), JSON.stringify([first, second]));
  fs.writeFileSync(path.join(out, 'result.json'), JSON.stringify({passed: true, checks: ['first-entry', 'name-only-creation', 'reload-restore', 'reopen-restore', 'project-switch', 'material-upload', 'record-save', 'unconfigured-ai', 'mobile-overflow', 'invalid-project-fallback', 'no-browser-errors']}));
  await browser.close();
  console.log('PASS: project-first browser flow, upload, synthetic recording, recovery and mobile layout');
})().catch(error => { console.error(error); process.exit(1); });
