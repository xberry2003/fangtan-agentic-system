FORMATS_BY_ID = {item["id"]: item for item in REPORT_FORMATS}
TEMPLATES_BY_ID = {item["id"]: item for item in REPORT_TEMPLATES}

REPORT_EVIDENCE_RULES = """资料范围和证据规则：
- 每个实质判断给出 [M1-P1] 形式的真实出处，至少引用每份原始材料一次；既有纪要、计划和模型输出不能当作原始证据。
- 资料范围区分访谈场次、原始材料份数和独立受访人数；同一人多次访谈不能按场次重复计人数。
- 区分访谈原话、研究发现、用户或业务洞察、需求机会、需求建议和待验证假设；个体诉求不能直接写成普遍需求。
- 涉及频次、影响、金额、规模或优先级时说明依据；没有数据就写“待确认/待补充”，不编造数字、来源或现场观察。
- 保留受访者之间的矛盾和反面证据；资料不足时把报告性质写成阶段性讨论稿，并列出下一步核实方式。"""


def normalize(format_id: str = "", template_id: str = ""):
    """返回（格式, 模板）；模板优先，并自动采用模板对应的格式。"""
    template = TEMPLATES_BY_ID.get((template_id or "").strip())
    if template_id and not template:
        raise ValueError("报告模板不存在")
    if template:
        return FORMATS_BY_ID[template["format"]], template
    fmt = FORMATS_BY_ID.get((format_id or "").strip())
    if format_id and not fmt:
        raise ValueError("报告格式不存在")
    return fmt, None


def public_options():
    return {
        "formats": [
            {"id": item["id"], "name": item["name"], "description": item["description"]}
            for item in REPORT_FORMATS
        ],
        "templates": [
            {
                "id": item["id"],
                "name": item["name"],
                "format": item["format"],
                "description": item["description"],
                "sections": [section["title"] for section in item["sections"] if section["level"] == 1],
            }
            for item in REPORT_TEMPLATES
        ],
    }


def display_name(format_id: str = "", template_id: str = "") -> str:
    try:
        fmt, template = normalize(format_id, template_id)
    except ValueError:
        return "调研整合报告"
    if template:
        return template["name"]
    if fmt:
        return fmt["name"]
    return "调研整合报告"


def report_guide(format_id: str = "", template_id: str = "") -> str:
    """生成给模型的报告章节指令；没有选择时返回空串，沿用默认整合报告。"""
    try:
        fmt, template = normalize(format_id, template_id)
    except ValueError:
        return ""
    if not fmt:
        return ""
    source = template or fmt
    kind = "固定模板" if template else "报告格式"
    lines = [
        f"用户选择了{kind}：{source['name']}。",
        f"请严格按照下面的章节顺序输出 Markdown；一级章节用 ##，二级用 ###，三级用 ####。",
        f"缺失资料的章节必须保留标题，并写明“本项材料未提供，待补充”，不得删除章节、改名或编造内容。",
        "模板中的表格用 Markdown 表格表达；没有数据时写“待确认”，不要生成虚构数据。",
        "报告开头用 # 输出报告标题，再用一小段封面信息标明报告日期、报告性质和资料范围；不要手写目录，工作台会根据标题生成目录。",
    ]
    for section in source["sections"]:
        lines.append(f"{'#' * (section['level'] + 1)} {section['title']}")
    lines.append(REPORT_EVIDENCE_RULES)
    return "\n".join(lines)
